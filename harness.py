def run_ast_policy_guard() -> List[str]:
    """
    Scans production python modules for prohibited simulation constructs:
    - import random / from random import ...
    - import faker / from faker import ...
    - ProceduralCaseSimulator usage
    Exempts test files and training scripts.
    """
    violations = []
    scan_targets = []

    # 1. Production package src, verification_engine, and vlm_context_engine
    if SRC_DIR.exists():
        for py_path in SRC_DIR.rglob("*.py"):
            scan_targets.append(py_path)
    if VERIFICATION_ENGINE_DIR.exists():
        for py_path in VERIFICATION_ENGINE_DIR.rglob("*.py"):
            scan_targets.append(py_path)
    if VLM_CONTEXT_ENGINE_DIR.exists():
        for py_path in VLM_CONTEXT_ENGINE_DIR.rglob("*.py"):
            if "test" in py_path.name.lower():
                continue
            scan_targets.append(py_path)

    # 2. Operational scripts (excluding training and build scripts)
    if SCRIPTS_DIR.exists():
        for py_path in SCRIPTS_DIR.rglob("*.py"):
            name = py_path.name.lower()
            parent = str(py_path).lower()
            if "training" in parent or "build_champion" in name or "test" in name:
                continue
            scan_targets.append(py_path)

    for target in scan_targets:
        try:
            with open(target, "r", encoding="utf-8", errors="replace") as f:
                content = f.read()
            tree = ast.parse(content, filename=str(target))
        except Exception as e:
            violations.append(f"AST parse error in {target}: {e}")
            continue

        for node in ast.walk(tree):
            # Check import random / faker
            if isinstance(node, ast.Import):
                for alias in node.names:
                    mod_name = alias.name.split(".")[0].lower()
                    if mod_name in ("random", "faker"):
                        violations.append(
                            f"{target}:{node.lineno} -> Prohibited 'import {alias.name}' detected"
                        )
            elif isinstance(node, ast.ImportFrom):
                mod_name = (node.module or "").split(".")[0].lower()
                if mod_name in ("random", "faker"):
                    violations.append(
                        f"{target}:{node.lineno} -> Prohibited 'from {node.module}' detected"
                    )
                for alias in node.names:
                    if alias.name in ("ProceduralCaseSimulator", "Faker"):
                        violations.append(
                            f"{target}:{node.lineno} -> Prohibited import of '{alias.name}'"
                        )
            elif isinstance(node, ast.Name):
                if node.id == "ProceduralCaseSimulator":
                    violations.append(
                        f"{target}:{node.lineno} -> Prohibited reference to 'ProceduralCaseSimulator'"
                    )

    return violations


def load_verified_citations_whitelist() -> Tuple[set, set, set, dict]:
    """Loads closed whitelist of verified court cases, agency letters, KoAP articles, federal laws, and context bindings."""
    wl_path = ROOT_DIR / "config" / "verified_citations_whitelist.yaml"
    if not wl_path.exists():
        wl_path = ROOT_DIR / "legal_sheaf_verifier" / "config" / "verified_citations_whitelist.yaml"
    if not wl_path.exists():
        return set(), set(), set(), {}
    try:
        with open(wl_path, "r", encoding="utf-8") as f:
            data = yaml.safe_load(f) or {}
        cases = set(data.get("verified_court_cases", []))
        letters = set(data.get("verified_agency_letters", []))
        koap_direct = data.get("verified_koap_articles", [])
        koap_nested = data.get("verified_koap_and_laws", {}).get("koap_articles", [])
        laws_direct = data.get("verified_federal_laws", [])
        laws_nested = data.get("verified_koap_and_laws", {}).get("federal_laws", [])
        context_bindings = data.get("citation_context_bindings", {})

        allowed_koap = set(str(x) for x in (koap_direct + koap_nested))
        allowed_laws = set(str(x) for x in (laws_direct + laws_nested))
        return (cases | letters), allowed_koap, allowed_laws, context_bindings
    except Exception as e:
        print(f"[!] Warning: Failed to load citations whitelist: {e}", file=sys.stderr)
        return set(), set(), set(), {}


def run_citation_whitelist_guard() -> List[str]:
    """
    Scans files across all project directories (src, visual_qc, verification_engine, scripts,
    config, reports, kits, review_desk, lawyer_validation) for court cases, agency letters,
    KoAP articles, and Semantic Citation Context bindings.
    """
    allowed_citations, allowed_koap, allowed_laws, context_bindings = load_verified_citations_whitelist()
    if not allowed_citations:
        return ["Verified citations whitelist is missing or empty!"]

    pat_soyu = re.compile(r"\b0?5-\d{3,5}/\d{2,4}/20\d{2}\b")
    pat_arbitr = re.compile(r"\b[АA]\d{2}-\d{3,7}/20\d{2}\b")
    pat_appeal = re.compile(r"\b\d{2}АП-\d{3,7}/20\d{2}\b")
    pat_letter = re.compile(r"\b(?:[А-ЯЁ]{2}|\d{2})/\d{4,6}/\d{2}\b")
    patterns = [pat_soyu, pat_arbitr, pat_appeal, pat_letter]

    pat_koap_art1 = re.compile(r"(?i)\b(?:ст\.|стать[еяию]\w*|ч\.\s*[\d,/-]+\s*ст\.)\s*(\d{1,2}\.\d{1,2}(?:\.\d+)?)\s*(?:КоАП|Кодекса)")
    pat_koap_art2 = re.compile(r"(?i)\b(\d{1,2}\.\d{1,2}(?:\.\d+)?)\s*КоАП")
    koap_patterns = [pat_koap_art1, pat_koap_art2]

    violations = []
    scan_dirs = [
        SRC_DIR,
        VERIFICATION_ENGINE_DIR,
        VLM_CONTEXT_ENGINE_DIR,
        SCRIPTS_DIR,
        ROOT_DIR / "legal_sheaf_verifier" / "config",
        DATA_DIR / "reports",
        DATA_DIR / "kits",
        DATA_DIR / "review_desk",
        DATA_DIR / "lawyer_validation",
    ]

    for sdir in scan_dirs:
        if not sdir.exists():
            continue
        for p in sdir.rglob("*"):
            if not p.is_file():
                continue
            # Skip test files, virtualenv, and the whitelist itself
            if "tests" in p.parts or p.name.startswith("test_") or "verified_citations_whitelist" in p.name:
                continue
            if p.suffix.lower() in (".py", ".yaml", ".yml", ".html", ".txt", ".md"):
                try:
                    with open(p, "r", encoding="utf-8", errors="replace") as f:
                        for line_no, line in enumerate(f, 1):
                            line_lower = line.lower()
                            for pat in patterns:
                                for m in pat.finditer(line):
                                    num = m.group(0)
                                    if num not in allowed_citations:
                                        violations.append(
                                            f"CITATION_HALLUCINATION_BLOCKED: {num} in {p}:{line_no}"
                                        )
                                    # Semantic Citation Context Lock
                                    if num in context_bindings:
                                        b_info = context_bindings[num]
                                        reqs = b_info.get("required_markers", [])
                                        for req in reqs:
                                            if req.lower() not in line_lower:
                                                violations.append(
                                                    f"SEMANTIC_CITATION_SPOOFING_BLOCKED: Missing required marker '{req}' for citation {num} in {p}:{line_no}"
                                                )
                                        forbs = b_info.get("forbidden_markers", [])
                                        for forb in forbs:
                                            if forb.lower() in line_lower:
                                                violations.append(
                                                    f"SEMANTIC_CITATION_SPOOFING_BLOCKED: Forbidden marker '{forb}' found for citation {num} in {p}:{line_no}"
                                                )

                            for pat_k in koap_patterns:
                                for m in pat_k.finditer(line):
                                    art = m.group(1)
                                    if art not in allowed_koap:
                                        violations.append(
                                            f"KOAP_ARTICLE_PROHIBITED_BLOCKED: {art} in {p}:{line_no}"
                                        )
                except Exception:
                    pass

    # Also scan records with is_verified_citation == True in legal_kb_seed/*.jsonl
    kb_dir = ROOT_DIR / "legal_sheaf_verifier" / "legal_kb_seed"
    if kb_dir.exists():
        for jf in kb_dir.glob("*.jsonl"):
            try:
                with open(jf, "r", encoding="utf-8", errors="replace") as f:
                    for line_no, line in enumerate(f, 1):
                        if not line.strip():
                            continue
                        item = json.loads(line)
                        if item.get("is_verified_citation") is True:
                            content_to_check = f"{item.get('doc_number', '')} {item.get('case_number', '')} {item.get('text', '')}"
                            for pat in patterns:
                                for m in pat.finditer(content_to_check):
                                    num = m.group(0)
                                    if num not in allowed_citations:
                                        violations.append(
                                            f"CITATION_HALLUCINATION_BLOCKED: {num} in {jf}:{line_no}"
                                        )
            except Exception:
                pass

    return violations


class HTMLDOMInspector(html.parser.HTMLParser):
    """
    Standard library HTML parser inspecting tag balance and detecting unparsed markdown.
    """
    def __init__(self, filepath: Path):
        super().__init__()
        self.filepath = filepath
        self.tag_stack: List[Tuple[str, int]] = []
        self.violations: List[str] = []
        self.void_tags = {"br", "hr", "img", "input", "meta", "link", "area", "base", "col", "embed", "param", "source", "track", "wbr"}
        self.inline_tags = {"strong", "code", "em", "b", "i", "u", "span"}

    def handle_starttag(self, tag: str, attrs: List[Tuple[str, Optional[str]]]):
        t = tag.lower()
        if t in self.void_tags:
            return
        self.tag_stack.append((t, self.getpos()[0]))

    def handle_endtag(self, tag: str):
        t = tag.lower()
        if t in self.void_tags:
            return
        line_no = self.getpos()[0]
        if not self.tag_stack:
            self.violations.append(f"ORACLE_I_DOM_ERROR_BLOCKED: Closing </{t}> without opening tag at line {line_no} in {self.filepath}")
            return

        if t in self.inline_tags:
            open_tags = [item[0] for item in self.tag_stack]
            if t not in open_tags:
                self.violations.append(f"ORACLE_I_DOM_ERROR_BLOCKED: Inverted or orphaned closing </{t}> at line {line_no} in {self.filepath}")
                return

        for i in range(len(self.tag_stack) - 1, -1, -1):
            if self.tag_stack[i][0] == t:
                del self.tag_stack[i:]
                return

    def handle_data(self, data: str):
        line_no = self.getpos()[0]
        current_tags = [item[0] for item in self.tag_stack]
        if any(tag in current_tags for tag in ("pre", "code", "script", "style")):
            return
        if "**" in data:
            self.violations.append(f"ORACLE_I_DOM_ERROR_BLOCKED: Unparsed Markdown '**' detected in HTML text at line {line_no} in {self.filepath}")
        if "`" in data:
            self.violations.append(f"ORACLE_I_DOM_ERROR_BLOCKED: Unparsed Markdown '`' detected in HTML text at line {line_no} in {self.filepath}")


def run_artifact_dom_guard() -> List[str]:
    """
    Oracle I: HTML/MD Artifact & Anti-Truncation Inspector.
    Scans C:\\AdRadarData\\lawyer_validation, kits, reports for:
    - Cleaned live document text (stripping <pre>, <code>, <script>, <style> blocks)
    - Inverted </strong> tags or unparsed markdown (** / `) inside HTML
    - Truncation markers ([Полный текст, truncated CSS/HTML, generic placeholders)
    - Internal ML jargon in client files under kits/ (LegalSheaf, Chronotope, Vega-U, etc.)
    - Legal hallucinations (contracts with liquidated entities, invalid OGRN, fake orders)
    """
    violations = []
    target_dirs = [
        DATA_DIR / "lawyer_validation",
        DATA_DIR / "kits",
        DATA_DIR / "reports",
    ]

    pat_inverted_tag = re.compile(r"(?:<p>|<td>|<li>)[^<]*</strong>", re.IGNORECASE)
    pat_unparsed_bold = re.compile(r"(?:<p>|<td>|<li>)[^<]*\*\*[^*]+?\*\*", re.IGNORECASE)
    pat_liquidated_contract = re.compile(r"(?i)договор(?:[^\.\n]{0,60})между ликвидированным")
    pat_invalid_ogrn = re.compile(r"\b1246900010996\b")
    pat_fake_order = re.compile(r"\b69-26-022263\b")

    truncation_markers = [
        "[Полный текст",
        "backgr\n",
        '<div class="contain\n',
        "Документ сгенерирован автоматически",
    ]

    banned_client_jargon = [
        "LegalSheaf",
        "Chronotope",
        "Vega-U",
        "Conformal",
        "TriState",
        "ONNX",
    ]

    for tdir in target_dirs:
        if not tdir.exists():
            continue
        for p in tdir.rglob("*"):
            if not p.is_file():
                continue
            if p.suffix.lower() not in (".html", ".md") and p.name != "outreach_draft.txt":
                continue

            try:
                content = p.read_text(encoding="utf-8", errors="replace")
            except Exception as e:
                violations.append(f"ORACLE_I_READ_ERROR: Could not read {p}: {e}")
                continue

            # Local path leak & price ban in client-facing documents
            is_lawyer = "lawyer_validation" in str(p).lower()
            if not is_lawyer:
                if p.name == "outreach_draft.txt" or p.name.lower() == "index.html":
                    content_lower = content.lower()
                    for leak_prefix in ("file:///", "c:\\", "c:/"):
                        if leak_prefix in content_lower:
                            violations.append(f"ORACLE_I_LOCAL_LEAK_BLOCKED: Local path/URI '{leak_prefix}' detected in {p}")
                if p.name == "outreach_draft.txt":
                    for price_pattern in ("14 900", "14900"):
                        if price_pattern in content:
                            violations.append(f"ORACLE_I_PRICE_SPAM_BLOCKED: Price offer '{price_pattern}' detected in cold outreach {p}")

            if p.suffix.lower() not in (".html", ".md"):
                continue

            # Strip out code, pre, script, and style blocks to prevent false alarms on sysadmin examples
            clean_text = re.sub(r"<(?:pre|code|script|style)[^>]*>.*?</(?:pre|code|script|style)>", "", content, flags=re.DOTALL | re.IGNORECASE)
            clean_text_no_fenced = re.sub(r"```.*?```", "", clean_text, flags=re.DOTALL)

            # 1. Truncation markers
            for tm in truncation_markers:
                if tm in clean_text_no_fenced:
                    violations.append(f"ORACLE_I_TRUNCATION_BLOCKED: '{tm}' detected in {p}")

            # 2. Legal hallucinations
            if pat_liquidated_contract.search(clean_text_no_fenced):
                violations.append(f"ORACLE_I_LEGAL_ERROR_BLOCKED: Contract with liquidated entity detected in {p}")
            if pat_invalid_ogrn.search(clean_text_no_fenced):
                violations.append(f"ORACLE_I_LEGAL_ERROR_BLOCKED: Erroneous OGRN 1246900010996 detected in {p}")
            if pat_fake_order.search(clean_text_no_fenced):
                violations.append(f"ORACLE_I_LEGAL_ERROR_BLOCKED: Invented order 69-26-022263 detected in {p}")

            # 3. Client kit jargon ban (kits/ only)
            if "kits" in str(p).lower():
                for j_term in banned_client_jargon:
                    if j_term in clean_text_no_fenced:
                        violations.append(f"ORACLE_I_JARGON_BLOCKED: Prohibited ML jargon '{j_term}' detected in client kit {p}")

            # 4. HTML formatting errors (for .html files)
            if p.suffix.lower() == ".html":
                inspector = HTMLDOMInspector(p)
                try:
                    inspector.feed(clean_text)
                    violations.extend(inspector.violations)
                except Exception:
                    pass

                if pat_inverted_tag.search(clean_text_no_fenced):
                    violations.append(f"ORACLE_I_DOM_ERROR_BLOCKED: Inverted </strong> tag detected in {p}")
                if pat_unparsed_bold.search(clean_text_no_fenced):
                    violations.append(f"ORACLE_I_DOM_ERROR_BLOCKED: Unparsed **bold** detected in {p}")

                # Check if first </strong> occurs before first <strong> in document body
                body_idx = clean_text_no_fenced.lower().find("<body")
                body_content = clean_text_no_fenced[body_idx:] if body_idx != -1 else clean_text_no_fenced
                f_open = body_content.find("<strong>")
                f_close = body_content.find("</strong>")
                if f_close != -1 and (f_open == -1 or f_close < f_open):
                    violations.append(f"ORACLE_I_DOM_ERROR_BLOCKED: Closing </strong> precedes opening <strong> in {p}")

    return violations


