def cmd_sync() -> int:
    """Synchronizes source packages into .venv, runs AST guard, and generates Code Map."""
    print("[*] [Harness Sync] Running Workspace Garbage Collector...")
    cleaned = garbage_collect_workspace()
    if cleaned:
        print(f"[+] [Harness Sync] Cleaned temporary workspace scripts: {', '.join(cleaned)}")

    print("[*] [Harness Sync] Synchronizing package sources into .venv...")

    if not SITE_PACKAGES.exists():
        print(f"[!] Site-packages not found: {SITE_PACKAGES}", file=sys.stderr)
        return 2

    # 1. Copy legal_sheaf, ingestion, verification_engine, and vlm_context_engine packages
    pkgs = [
        (SRC_DIR / "legal_sheaf", SITE_PACKAGES / "legal_sheaf"),
        (SRC_DIR / "ingestion", SITE_PACKAGES / "ingestion"),
        (VERIFICATION_ENGINE_DIR, SITE_PACKAGES / "verification_engine"),
        (VLM_CONTEXT_ENGINE_DIR, SITE_PACKAGES / "vlm_context_engine"),
    ]

    copied_files = 0
    pruned_files = 0
    for src_pkg, dest_pkg in pkgs:
        if src_pkg.exists():
            dest_pkg.mkdir(parents=True, exist_ok=True)
            src_rels = {item.relative_to(src_pkg) for item in src_pkg.rglob("*.py")}
            for existing in list(dest_pkg.rglob("*.py")):
                if existing.relative_to(dest_pkg) not in src_rels:
                    existing.unlink(missing_ok=True)
                    pruned_files += 1
                    cache_dir = existing.parent / "__pycache__"
                    if cache_dir.exists():
                        for pyc in cache_dir.glob(f"{existing.stem}.*.pyc"):
                            pyc.unlink(missing_ok=True)
            for item in src_pkg.rglob("*.py"):
                rel_path = item.relative_to(src_pkg)
                target_file = dest_pkg / rel_path
                target_file.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(item, target_file)
                # Compile to catch syntax errors immediately
                try:
                    py_compile.compile(str(target_file), doraise=True)
                    copied_files += 1
                except py_compile.PyCompileError as e:
                    print(f"[!] Syntax error compiling {target_file}: {e}", file=sys.stderr)
                    return 2
    if pruned_files:
        print(f"    Pruned {pruned_files} stale .py file(s) from .venv site-packages.")

    # Sync top-level showcase_server module into site-packages
    showcase_src = SRC_DIR / "showcase_server.py"
    if showcase_src.exists():
        showcase_dest = SITE_PACKAGES / "showcase_server.py"
        shutil.copy2(showcase_src, showcase_dest)
        try:
            py_compile.compile(str(showcase_dest), doraise=True)
            copied_files += 1
        except py_compile.PyCompileError as e:
            print(f"[!] Syntax error compiling {showcase_dest}: {e}", file=sys.stderr)
            return 2

    # Also compile all scripts in scripts/ to ensure syntax validity
    if SCRIPTS_DIR.exists():
        for script_file in SCRIPTS_DIR.rglob("*.py"):
            try:
                py_compile.compile(str(script_file), doraise=True)
                copied_files += 1
            except py_compile.PyCompileError as e:
                print(f"[!] Syntax error compiling script {script_file}: {e}", file=sys.stderr)
                return 2

    print(f"[+] [Harness Sync] {copied_files} files synchronized and bytecode-compiled.")

    # 2. Run AST Static Policy Guard
    print("[*] [Harness Sync] Running AST Static Policy Guard...")
    ast_violations = run_ast_policy_guard()
    if ast_violations:
        print("[!] [AST GUARD FAIL] Prohibited simulation constructs detected in production code:", file=sys.stderr)
        for v in ast_violations:
            print(f"    • {v}", file=sys.stderr)
        return 2

    print("[+] [Harness Sync] AST Static Policy Guard: PASSED (Zero-Mock strictly verified).")

    # 3. Run Citation Whitelist Guard
    print("[*] [Harness Sync] Running Citation Whitelist Guard...")
    citation_violations = run_citation_whitelist_guard()
    if citation_violations:
        print("[!] [CITATION GUARD FAIL] Unverified or hallucinated citation detected:", file=sys.stderr)
        for v in citation_violations:
            print(f"    • {v}", file=sys.stderr)
        return 2

    print("[+] [Harness Sync] Citation Whitelist Guard: PASSED (Zero hallucinated citations).")

    # 4. Generate Code Map (.agents/CODE_MAP.md)
    print("[*] [Harness Sync] Generating AST Code Map (.agents/CODE_MAP.md)...")
    code_map_file = ROOT_DIR / ".agents" / "CODE_MAP.md"
    n_files, n_syms = generate_ast_code_map(code_map_file)
    size_kb = round(code_map_file.stat().st_size / 1024, 1) if code_map_file.exists() else 0.0
    print(f"[+] [Harness Sync] Code Map updated: .agents/CODE_MAP.md ({n_files} files, {n_syms} symbols, {size_kb} KB).")
    return 0


