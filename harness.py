def cmd_probe(script_path: str) -> int:
    """Executes a diagnostic python script safely with UTF-8 encoding."""
    target = Path(script_path).resolve()
    if not target.exists():
        print(f"[!] Probe script not found: {target}", file=sys.stderr)
        return 2

    env = os.environ.copy()
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    if SRC_DIR.exists():
        env["PYTHONPATH"] = f"{SRC_DIR};{env.get('PYTHONPATH', '')}"

    cmd = [str(VENV_PYTHON), str(target)]
    print(f"[*] [Harness Probe] Running probe script: {target}")
    res = subprocess.run(cmd, env=env)
    return res.returncode


