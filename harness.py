def cmd_gate() -> int:
    """Executes the full acceptance pipeline: Gates 1 through 4."""
    print("\n" + "=" * 65)
    print("               ADRADAR ACCEPTANCE GATE PIPELINE                ")
    print("=" * 65)

    # -------------------------------------------------------------------------
    # [Gate 1: Sync & AST Guard]
    # -------------------------------------------------------------------------
    print("\n[Gate 1/4] Running Code Sync & AST Static Policy Guard...")
    if cmd_sync() != 0:
        print("\n[GATE FAIL] Gate 1 (Sync & AST Guard) FAILED.", file=sys.stderr)
        return 2
    print("[+] Gate 1: PASSED.")

    # -------------------------------------------------------------------------
    # [Gate 2: Pytest Suite]
    # -------------------------------------------------------------------------
    print("\n[Gate 2/4] Running Pytest Suite (legal_sheaf_verifier/tests + vlm_context_engine/tests)...")
    test_cmd = [str(VENV_PYTHON), "-m", "pytest", "legal_sheaf_verifier/tests", "vlm_context_engine/tests", "-q"]
    res_test = subprocess.run(test_cmd)
    if res_test.returncode != 0:
        print(f"\n[GATE FAIL] Gate 2 (Pytest Suite) FAILED with exit code {res_test.returncode}.", file=sys.stderr)
        return 2
    print("[+] Gate 2: PASSED.")

    # -------------------------------------------------------------------------
    # [Gate 3: System Doctor & Live Canaries]
    # -------------------------------------------------------------------------
    print("\n[Gate 3/4] Running System Doctor & Live Canaries...")
    doc_cmd = [str(VENV_ADRADAR), "doctor", "--live-canaries"]
    res_doc = subprocess.run(doc_cmd)
    if res_doc.returncode != 0:
        print(f"\n[GATE FAIL] Gate 3 (System Doctor & Canaries) FAILED with exit code {res_doc.returncode}.", file=sys.stderr)
        return 2
    print("[+] Gate 3: PASSED.")

    # -------------------------------------------------------------------------
    # [Gate 4: Semantic Business Oracles]
    # -------------------------------------------------------------------------
    print("\n[Gate 4/4] Evaluating Semantic Business Oracles (A, B, C, D, E, F, G, H, I, J)...")
    passed, oracle_failures = asyncio.run(evaluate_semantic_business_oracles())
    if not passed:
        print("\n[GATE FAIL] Gate 4 (Semantic Business Oracles) FAILED:", file=sys.stderr)
        for f in oracle_failures:
            print(f"    • {f}", file=sys.stderr)
        return 2
    print("[+] Gate 4: PASSED.")

    # -------------------------------------------------------------------------
    # FINAL DYNAMIC CERTIFICATION HASH
    # -------------------------------------------------------------------------
    hasher = hashlib.sha256()

    # 1. Hashes of all synced production .py files (sorted deterministically)
    core_files = []
    for pkg_dir in [SRC_DIR, VERIFICATION_ENGINE_DIR, VLM_CONTEXT_ENGINE_DIR]:
        if pkg_dir.exists():
            for f in sorted(pkg_dir.rglob("*.py")):
                if "test" in f.name.lower():
                    continue
                core_files.append(f)
    for cf in core_files:
        try:
            rel_name = str(cf.relative_to(ROOT_DIR)).replace("\\", "/")
            hasher.update(rel_name.encode("utf-8"))
            hasher.update(cf.read_bytes())
        except Exception:
            pass

    # 2. Hash of champion_v3.bundle
    bundle_path = DATA_DIR / "models" / "champion_v3.bundle"
    if not bundle_path.exists():
        bundle_path = ROOT_DIR / "legal_sheaf_verifier" / "artifacts" / "champion_v3.bundle"
    if bundle_path.exists():
        hasher.update(bundle_path.name.encode("utf-8"))
        hasher.update(bundle_path.read_bytes()[:65536])

    # 3. Hash of all 10 oracle statuses
    oracle_proof = f"ORACLES_PASSED:A,B,C,D,E,F,G,H,I,J:FAILURES={len(oracle_failures)}"
    hasher.update(oracle_proof.encode("utf-8"))

    cert_hash = hasher.hexdigest()[:16]
    print("\n" + "=" * 65)
    print(f"HARNESS_GATE_STATUS: PASSED (Cert Hash: {cert_hash})")
    print("All contracts, live canaries, and business oracles certified.")
    print("=" * 65 + "\n")
    return 0


