def format_ast_args(args_node: ast.arguments) -> str:
    """Formats function/method arguments into a clean signature string."""
    parts = []
    for a in args_node.args:
        parts.append(a.arg)
    if args_node.vararg:
        parts.append(f"*{args_node.vararg.arg}")
    elif args_node.kwonlyargs:
        parts.append("*")
    for a in args_node.kwonlyargs:
        parts.append(a.arg)
    if args_node.kwarg:
        parts.append(f"**{args_node.kwarg.arg}")
    return ", ".join(parts)


def generate_ast_code_map(output_path: Path) -> Tuple[int, int]:
    """
    Parses all python files in project via ast.parse and generates a concise,
    ground-truth structural index in .agents/CODE_MAP.md.
    Returns (num_files, num_symbols).
    """
    scan_roots = [
        SRC_DIR,
        VERIFICATION_ENGINE_DIR,
        VLM_CONTEXT_ENGINE_DIR,
        SCRIPTS_DIR,
    ]
    py_files = []
    for r in scan_roots:
        if r.exists():
            for pf in sorted(r.rglob("*.py")):
                if "__pycache__" in str(pf):
                    continue
                py_files.append(pf)

    for extra in [ROOT_DIR / "harness.py", ROOT_DIR / "cli.py"]:
        if extra.exists():
            py_files.append(extra)

    lines = [
        "# AdRadar Architecture Code Map",
        "",
        "> **AUTO-GENERATED by `harness.py sync` via AST parser.**",
        "> Ground truth symbol index: file -> classes -> methods/functions with line numbers and arguments.",
        "> **Rule**: Before searching functions with grep/find, inspect exact line ranges in this document.",
        "",
    ]

    total_symbols = 0
    total_files = 0

    for pf in py_files:
        try:
            rel_path = str(pf.relative_to(ROOT_DIR)).replace("\\", "/")
        except ValueError:
            rel_path = str(pf).replace("\\", "/")

        try:
            content = pf.read_text(encoding="utf-8", errors="replace")
            tree = ast.parse(content, filename=str(pf))
        except Exception:
            continue

        file_symbols = []
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                total_symbols += 1
                doc = ast.get_docstring(node) or ""
                doc_first = doc.strip().split("\n")[0] if doc else ""
                end_lineno = getattr(node, "end_lineno", node.lineno)
                doc_str = f" - {doc_first}" if doc_first else ""
                class_entry = f"- `class {node.name}` (L{node.lineno}-L{end_lineno}){doc_str}"
                method_entries = []
                for sub in node.body:
                    if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        total_symbols += 1
                        m_prefix = "async def" if isinstance(sub, ast.AsyncFunctionDef) else "def"
                        args_str = format_ast_args(sub.args)
                        m_doc = ast.get_docstring(sub) or ""
                        m_first = m_doc.strip().split("\n")[0] if m_doc else ""
                        m_doc_str = f" - {m_first}" if m_first else ""
                        method_entries.append(f"  - `{m_prefix} {sub.name}({args_str})` (L{sub.lineno}){m_doc_str}")
                file_symbols.append((class_entry, method_entries))

            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                total_symbols += 1
                f_prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
                args_str = format_ast_args(node.args)
                doc = ast.get_docstring(node) or ""
                doc_first = doc.strip().split("\n")[0] if doc else ""
                doc_str = f" - {doc_first}" if doc_first else ""
                file_symbols.append((f"- `{f_prefix} {node.name}({args_str})` (L{node.lineno}){doc_str}", []))

        if file_symbols:
            total_files += 1
            lines.append(f"## `{rel_path}`")
            for main_entry, sub_entries in file_symbols:
                lines.append(main_entry)
                for sub in sub_entries:
                    lines.append(sub)
            lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return total_files, total_symbols


