def extract_body_content(html_str: str) -> str:
    """Extracts the <body> content and strips out <style>...</style>."""
    clean = re.sub(r"<style[^>]*>.*?</style>", "", html_str, flags=re.DOTALL | re.IGNORECASE)
    m = re.search(r"<body[^>]*>(.*?)</body>", clean, flags=re.DOTALL | re.IGNORECASE)
    if m:
        return m.group(1).strip()
    clean = re.sub(r"<!DOCTYPE[^>]*>", "", clean, flags=re.IGNORECASE)
    clean = re.sub(r"</?(?:html|head|meta|title)[^>]*>", "", clean, flags=re.IGNORECASE)
    return clean.strip()


def load_yaml_config(rel_path: str) -> Dict[str, Any]:
    base_dir = Path(__file__).resolve().parent.parent.parent
    p = base_dir / rel_path
    if not p.exists():
        p = Path(rel_path)
    if p.exists():
        with open(p, "r", encoding="utf-8") as f:
            return yaml.safe_load(f) or {}
    return {}


def load_jsonl(rel_path: str) -> List[Dict[str, Any]]:
    base_dir = Path(__file__).resolve().parent.parent.parent
    p = base_dir / rel_path
    if not p.exists():
        p = Path(rel_path)
    items = []
    if p.exists():
        with open(p, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if line:
                    try:
                        items.append(json.loads(line))
                    except Exception:
                        pass
    return items


